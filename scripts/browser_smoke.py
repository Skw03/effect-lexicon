"""Run with an existing Python Playwright + Chromium installation; no package download.
Usage: python3 scripts/browser_smoke.py (start npm run dev first).
"""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

BASE = 'http://127.0.0.1:5173'
results = []
def check(name, condition=True):
    assert condition, name
    results.append(name)
    print('PASS', name, flush=True)

def set_range(page, key, value):
    slider = page.locator('#param-' + key)
    slider.fill(str(value))
    slider.dispatch_event('input')
    slider.dispatch_event('change')

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width':1280,'height':900}, permissions=['clipboard-read','clipboard-write'])
    page = context.new_page()
    errors = []
    external = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.on('request', lambda request: external.append(request.url) if not request.url.startswith(BASE) else None)
    page.goto(BASE)
    expect(page.locator('main a.effect-title')).to_have_count(10)
    check('Library has exactly ten canonical effect entries', page.locator('main a.effect-title').evaluate_all('(links) => links.map(link => link.getAttribute("href"))') == ['/effects/card-tilt-3d', '/effects/typewriter', '/effects/glassmorphism', '/effects/card-flip', '/effects/spotlight-card', '/effects/magnetic-button', '/effects/ripple-button', '/effects/sliding-fill-button', '/effects/gradient-text-shimmer', '/effects/staggered-text-reveal'])
    for slug in ['card-tilt-3d','typewriter','glassmorphism']:
        page.goto(BASE + '/effects/' + slug)
        expect(page.locator('h1')).to_be_visible()
        check(slug + ' real detail and controls', page.locator('.demo-stage').count() == 1 and page.locator('input[type=range]').count() >= 3)
        check(slug + ' no unpublished related dead links', page.locator('a[href^="/effects/"]').evaluate_all('(links) => links.map(a => a.getAttribute("href"))') == {'card-tilt-3d':['/effects/card-flip','/effects/spotlight-card'], 'typewriter':['/effects/gradient-text-shimmer','/effects/staggered-text-reveal'], 'glassmorphism':[]}[slug])
        for lang, label in [('en','English'),('zh','中文')]:
            page.get_by_role('button', name=label, exact=True).click()
            key, value = {'card-tilt-3d':('maxTilt',20),'typewriter':('typingSpeed',100),'glassmorphism':('blur',30)}[slug]
            set_range(page,key,value)
            prompt = page.locator('#prompt').input_value()
            check(slug + ' live ' + lang + ' parameter prompt', str(value) + {'maxTilt':'deg','typingSpeed':'ms','blur':'px'}[key] in prompt)
            page.get_by_role('button',name='复制提示词',exact=True).click()
            expect(page.locator('p[role=status]')).to_have_text('已复制到剪贴板')
            check(slug + ' exact ' + lang + ' clipboard', page.evaluate('navigator.clipboard.readText()') == prompt)
        page.reload()
        check(slug + ' language preference survives reload', page.get_by_role('button',name='中文',exact=True).get_attribute('aria-pressed') == 'true')
    page.goto(BASE+'/effects/card-tilt-3d')
    stage = page.locator('.tilt-area'); stage.scroll_into_view_if_needed()
    box = stage.bounding_box()
    page.mouse.move(box['x']+box['width']*.85,box['y']+box['height']*.7)
    page.wait_for_timeout(250)
    check('tilt follows pointer', 'rotateY(0deg)' not in page.locator('.tilt-card').get_attribute('style'))
    page.mouse.move(0,0); page.wait_for_timeout(450)
    stage.focus(); stage.press('ArrowRight'); page.wait_for_timeout(250)
    check('tilt keyboard equivalent', 'rotateY(0deg)' not in page.locator('.tilt-card').get_attribute('style'))
    check('visible keyboard focus', stage.evaluate('el => getComputedStyle(el).outlineWidth') == '2px')
    stage.press('Escape'); page.wait_for_timeout(450)
    check('Escape returns flat', 'rotateY(0deg)' in page.locator('.tilt-card').get_attribute('style'))
    page.locator('#param-glare').uncheck()
    check('glare disabled in demo and prompt', page.locator('.tilt-glare').count() == 0 and '25%' not in page.locator('#prompt').input_value())
    page.get_by_role('button',name='自动演示 Auto demo',exact=True).click(); page.wait_for_timeout(350)
    check('Auto demo moves and exposes Stop', page.get_by_role('button',name='停止 Stop').count() == 1 and 'rotateY(0deg)' not in page.locator('.tilt-card').get_attribute('style'))
    page.get_by_role('button',name='停止 Stop').click()
    expect(page.get_by_role('button',name='自动演示 Auto demo')).to_be_visible()
    page.get_by_role('button',name='重置 Reset').click()
    check('Reset restores tilt parameters', page.locator('#param-glare').is_checked() and page.locator('#param-maxTilt').input_value() == '12')
    page.goto(BASE+'/effects/typewriter')
    page.locator('.typewriter').scroll_into_view_if_needed()
    page.wait_for_timeout(1250)
    text1=page.locator('.typewriter').inner_text()
    page.get_by_role('button',name='暂停 Pause').click()
    paused=page.locator('.typewriter').inner_text(); page.wait_for_timeout(700)
    check('Pause freezes typed text', page.locator('.typewriter').inner_text() == paused)
    page.get_by_role('button',name='重播 Replay').click()
    check('Replay restarts text', page.locator('.typewriter').inner_text() == '│')
    set_range(page,'typingSpeed',20); set_range(page,'deleteSpeed',10); set_range(page,'pauseAfter',500)
    page.locator('#param-loop').uncheck()
    page.get_by_role('button',name='重播 Replay').click()
    page.locator('.typewriter').scroll_into_view_if_needed()
    expect(page.locator('.typewriter')).to_have_attribute('data-phase','done',timeout=10000)
    check('non-loop keeps third phrase', page.locator('.typewriter').inner_text() == '从看见到实现│')
    page.locator('#param-loop').check(); page.get_by_role('button',name='重播 Replay').click()
    page.locator('.typewriter').scroll_into_view_if_needed(); page.wait_for_timeout(6000)
    check('normal looping continues', page.locator('.typewriter').get_attribute('data-phase') != 'done')
    page.locator('#prompt').scroll_into_view_if_needed(); page.wait_for_timeout(150)
    offscreen=page.locator('.typewriter').inner_text(); page.wait_for_timeout(800)
    check('offscreen typewriter pauses',page.locator('.typewriter').inner_text()==offscreen)
    page.locator('.typewriter').scroll_into_view_if_needed()
    page.keyboard.press('Control+Home')
    page.locator('body').click(position={'x':5,'y':5})
    reachable=set()
    for _ in range(30):
        page.keyboard.press('Tab')
        reachable.add(page.evaluate('document.activeElement.id || document.activeElement.textContent'))
    check('keyboard reaches parameter and language/copy controls', 'param-loop' in reachable and 'param-typingSpeed' in reachable and 'English' in reachable and '复制提示词' in reachable)

    page.goto(BASE+'/effects/glassmorphism')
    set_range(page,'blur',32); set_range(page,'fillOpacity',.25); set_range(page,'borderOpacity',.5); set_range(page,'radius',24)
    style=page.locator('.glass-card').evaluate('el => ({blur:getComputedStyle(el).backdropFilter,fill:getComputedStyle(el).backgroundColor,border:getComputedStyle(el).borderColor,radius:getComputedStyle(el).borderRadius})')
    check('all four glass parameters update actual CSS', '32px' in style['blur'] and '0.25' in style['fill'] and '0.5' in style['border'] and style['radius']=='24px')
    for name in ['条纹色块','柔和光斑','彩色渐变']:
        page.get_by_role('button',name=name,exact=True).click()
        check('glass background '+name, page.get_by_role('button',name=name,exact=True).get_attribute('aria-pressed')=='true')
    check('glass honestly labelled static', page.get_by_text('视觉样式 · 无动画',exact=True).count()==1)
    # Exercise both clipboard fallback outcomes in the real browser.
    page.evaluate("Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:()=>Promise.reject(new Error('test denial'))}})")
    page.get_by_role('button',name='复制提示词',exact=True).click()
    expect(page.locator('p[role=status]')).to_have_text('已复制到剪贴板')
    check('clipboard execCommand fallback works')
    page.wait_for_timeout(2100)
    page.evaluate("document.execCommand=()=>false")
    page.get_by_role('button',name='复制提示词',exact=True).click()
    expect(page.locator('p[role=status]')).to_have_text('复制失败，请手动选择文本')
    check('copy failure selects full prompt', page.locator('#prompt').evaluate('el=>el.selectionStart===0 && el.selectionEnd===el.value.length && document.activeElement===el'))
    for width in [320,768,1280]:
        page.set_viewport_size({'width':width,'height':900})
        for slug in ['card-tilt-3d','typewriter','glassmorphism']:
            page.goto(BASE+'/effects/'+slug)
            check(f'{slug} no page overflow at {width}',page.evaluate('document.documentElement.scrollWidth<=window.innerWidth'))
    for path in ['/unknown','/effects/no-such-effect','/guide']:
        page.goto(BASE+path)
        expect(page.get_by_role('heading',name='找不到这个页面')).to_be_visible()
        check('Not Found '+path)
    check('no browser runtime exceptions',not errors)
    check('no external runtime requests',not external)
    reduced=browser.new_context(reduced_motion='reduce',viewport={'width':1280,'height':900})
    r=reduced.new_page(); r.goto(BASE+'/effects/typewriter'); r.locator('.typewriter').scroll_into_view_if_needed()
    text=r.locator('.typewriter').inner_text(); r.wait_for_timeout(1400)
    check('reduced motion initial full static phrase and no blinking',text=='让灵感逐字出现│' and text==r.locator('.typewriter').inner_text() and r.locator('.caret.blink').count()==0)
    set_range(r,'typingSpeed',20); set_range(r,'deleteSpeed',10); set_range(r,'pauseAfter',500)
    r.get_by_role('button',name='播放 Play').click(); r.locator('.typewriter').scroll_into_view_if_needed()
    expect(r.locator('.typewriter')).to_have_attribute('data-phase','done',timeout=10000)
    r.wait_for_timeout(1000)
    check('reduced manual Play runs three phrases once despite loop=true',r.locator('.typewriter').inner_text()=='从看见到实现│' and r.locator('.caret.blink').count()==0)
    r.get_by_role('button',name='重播 Replay').click()
    check('reduced manual Replay available',r.locator('.typewriter').get_attribute('data-phase')!='done')
    r.goto(BASE+'/effects/card-tilt-3d'); r.locator('.tilt-area').scroll_into_view_if_needed()
    r.locator('.tilt-area').hover(); r.wait_for_timeout(250)
    check('reduced pointer does not animate', 'rotateY(0deg)' in r.locator('.tilt-card').get_attribute('style'))
    r.get_by_role('button',name='自动演示 Auto demo').click(); r.wait_for_timeout(500)
    check('reduced Auto demo explicitly moves','rotateY(0deg)' not in r.locator('.tilt-card').get_attribute('style'))
    expect(r.get_by_role('button',name='自动演示 Auto demo')).to_be_visible(timeout=6000)
    check('reduced Auto demo returns to rest after one path','rotateY(0deg)' in r.locator('.tilt-card').get_attribute('style'))
    touch=browser.new_context(viewport={'width':375,'height':812},is_mobile=True,has_touch=True)
    t=touch.new_page(); t.goto(BASE+'/effects/card-tilt-3d'); t.locator('.tilt-area').scroll_into_view_if_needed()
    box=t.locator('.tilt-area').bounding_box(); cdp=touch.new_cdp_session(t)
    x=box['x']+box['width']*.3; y=box['y']+box['height']*.5
    cdp.send('Input.dispatchTouchEvent',{'type':'touchStart','touchPoints':[{'x':x,'y':y}]})
    cdp.send('Input.dispatchTouchEvent',{'type':'touchMove','touchPoints':[{'x':x+35,'y':y}]})
    t.wait_for_timeout(200)
    check('real browser touch drag tilts','rotateY(0deg)' not in t.locator('.tilt-card').get_attribute('style'))
    cdp.send('Input.dispatchTouchEvent',{'type':'touchEnd','touchPoints':[]})
    before=t.evaluate('scrollY'); box=t.locator('.tilt-area').bounding_box(); x=box['x']+40; y=box['y']+130
    cdp.send('Input.dispatchTouchEvent',{'type':'touchStart','touchPoints':[{'x':x,'y':y}]})
    for delta in [20,40,70,100]: cdp.send('Input.dispatchTouchEvent',{'type':'touchMove','touchPoints':[{'x':x,'y':y-delta}]})
    cdp.send('Input.dispatchTouchEvent',{'type':'touchEnd','touchPoints':[]}); t.wait_for_timeout(300)
    check('vertical touch swipe scrolls page', t.evaluate('scrollY')>before)
    check('touch controls have 44px targets',t.locator('button,input,a').evaluate_all('nodes=>nodes.every(el=>el.getBoundingClientRect().height>=44)'))
    check('touch hint used',t.locator('.touch-hint').is_visible() and not t.locator('.fine-hint').is_visible())
    Path('/tmp/effect-stage1-browser.json').write_text(json.dumps({'passed':len(results),'checks':results,'pageErrors':errors,'externalRequests':external},ensure_ascii=False,indent=2))
    print('TOTAL',len(results),'browser checks passed')
    browser.close()
